export function esc(s) {
  return String(s ?? "").replace(/[&<>"']/g, (c) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"
  }[c]));
}

export const HARI = ["Minggu", "Senin", "Selasa", "Rabu", "Kamis", "Jumat", "Sabtu"];
export const HARI_SINGKAT = ["Min", "Sen", "Sel", "Rab", "Kam", "Jum", "Sab"];
export const BULAN = ["Januari", "Februari", "Maret", "April", "Mei", "Juni", "Juli", "Agustus", "September", "Oktober", "November", "Desember"];

export function todayStr() {
  const d = new Date();
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
}
export function nowHM() {
  const d = new Date();
  return `${String(d.getHours()).padStart(2, "0")}:${String(d.getMinutes()).padStart(2, "0")}`;
}
export function nowHMS() {
  const d = new Date();
  return `${String(d.getHours()).padStart(2, "0")}:${String(d.getMinutes()).padStart(2, "0")}:${String(d.getSeconds()).padStart(2, "0")}`;
}
export function formatDateId(dateStr) {
  const [y, m, d] = dateStr.split("-").map(Number);
  const dt = new Date(y, m - 1, d);
  return `${HARI[dt.getDay()]}, ${d} ${BULAN[m - 1]} ${y}`;
}
export function hariIndo(dayNum) { return HARI[dayNum]; }
export function hariSingkat(dayNum) { return HARI_SINGKAT[dayNum]; }
export function todayDayNum() { return new Date().getDay(); }
export function minOfDay(hm) {
  const [h, m] = String(hm).split(":").map(Number);
  return h * 60 + m;
}
export function currentActivity(list) {
  const now = minOfDay(nowHM());
  let cur = null, next = null;
  for (const it of [...list].sort((a, b) => minOfDay(a.jamMulai) - minOfDay(b.jamMulai))) {
    const s = minOfDay(it.jamMulai), e = minOfDay(it.jamSelesai);
    if (now >= s && now < e) cur = it;
    if (minOfDay(it.jamMulai) > now && !next) next = it;
  }
  return { cur, next };
}
export function genId(prefix) {
  return `${prefix}-${Date.now()}-${Math.random().toString(36).slice(2, 7)}`;
}
export function fmtBytes(n) {
  if (!n) return "0 B";
  if (n < 1024) return n + " B";
  if (n < 1048576) return (n / 1024).toFixed(1) + " KB";
  return (n / 1048576).toFixed(1) + " MB";
}
export function initials(name) {
  return String(name || "?").split(" ").filter(Boolean).slice(0, 2).map((w) => w[0]).join("").toUpperCase();
}
export function avatarClass(name) {
  const n = (initials(name).charCodeAt(0) || 65);
  const cls = ["av-green", "av-gray", "av-gold", "av-blue"];
  return cls[n % cls.length];
}

/* ---------- Toast ---------- */
export function toast(msg, type = "success") {
  const root = $("#toast-root");
  const el = document.createElement("div");
  el.className = "toast" + (type === "error" ? " error" : "");
  el.textContent = msg;
  root.appendChild(el);
  setTimeout(() => {
    el.style.transition = "opacity .3s, transform .3s";
    el.style.opacity = "0";
    el.style.transform = "translateY(10px)";
    setTimeout(() => el.remove(), 320);
  }, 2600);
}

/* ---------- Modal ---------- */
export function openModal(html) {
  const root = $("#modal-root");
  root.innerHTML = `<div class="overlay"></div><div class="sheet">${html}</div>`;
  root.classList.add("open");
  $(".overlay").addEventListener("click", closeModal);
  return $(".sheet");
}
export function closeModal() {
  $("#modal-root").classList.remove("open");
  $("#modal-root").innerHTML = "";
}
export function confirmDialog(msg, opts = {}) {
  return new Promise((resolve) => {
    openModal(`
      <div class="sheet-head"><div class="sheet-title">Konfirmasi</div>
        <button class="sheet-x" data-close>${ic("x")}</button></div>
      <p style="font-size:14.5px;line-height:1.5">${esc(msg)}</p>
      <div style="display:flex;gap:10px;margin-top:18px">
        <button class="btn btn-outline" style="flex:1" data-no>Batal</button>
        <button class="btn btn-danger" style="flex:1" data-yes>Ya, ${esc(opts.ya || "lanjutkan")}</button>
      </div>`);
    const close = (v) => { closeModal(); resolve(v); };
    $("[data-yes]").addEventListener("click", () => close(true));
    $("[data-no]").addEventListener("click", () => close(false));
    $("[data-close]").addEventListener("click", () => close(false));
  });
}

